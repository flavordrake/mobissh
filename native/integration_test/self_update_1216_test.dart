// Setup (run FIRST): scripts/self-update-1216-setup.sh
// Teardown (always): scripts/self-update-1216-teardown.sh
//
// A5 — on-device self-update, end to end through the REAL `mobissh/updates`
// channel (#1216, spec docs/self-update.md R8-R11).
//
// The manifest + APK are served by an in-process http MockClient (the network
// is not what is under test; the device's PackageManager is), through the real
// checker → banner → installer → Kotlin verify → installer hand-off. Three
// builds are offered in turn:
//
//   1. FOREIGN PACKAGE (com.flavordrake.notmobissh) → R10 refuses on the
//      package name; the downloaded file is gone.
//   2. FOREIGN KEY (com.flavordrake.mobissh signed by a throwaway key) → R10
//      refuses on the signing certificate; the file is gone. Its sha256 DOES
//      match the manifest: this is exactly the "host is compromised" case the
//      sha alone cannot catch.
//   3. OUR OWN APK (this test app's base.apk: same package, same key),
//      PRE-DOWNLOADED (#1258 R14: the banner reads "Update ready" before any
//      tap), then ONE Install tap → no second download → R10 accepts and the
//      hand-off reaches the SYSTEM PACKAGE INSTALLER: the
//      intent resolves to a package installer and this activity leaves the
//      resumed state because the installer screen took the foreground. The
//      teardown records the resumed activity + a screenshot as evidence.
//
// #1258 R16 runs FIRST (before any installer covers the app): a stored
// last-run build lower than the running one plus pending notes → "Updated to
// <version>" → What's new shows the notes → a relaunch shows nothing.
//
// The two foreign stubs are committed bytes
// (fixtures/self_update_apks.dart, regenerated by
// scripts/gen-self-update-fixture-apks.sh). The setup script keeps the
// "install unknown apps" appop granted, which a test cannot toggle itself.
//
// Run: EMU_LEASE_WAIT=3600 scripts/with-fleet-emulator.sh -- \
//        scripts/integration-subset.sh integration_test/self_update_1216_test.dart
// No SSH session is needed — this test never connects.

